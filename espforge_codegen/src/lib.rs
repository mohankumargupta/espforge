/// Generates the content for the project's lib.rs
pub fn generate_lib_source() -> Result<String> {
    let tokens = quote! {
        #![no_std]
        pub mod app;
        pub mod generated;

        pub mod prelude {
            pub use embedded_hal::digital::{InputPin, OutputPin, StatefulOutputPin};
            pub use embedded_hal::delay::DelayNs;
            pub use embedded_hal::i2c::I2c;
            pub use embedded_hal::spi::SpiBus;
            pub use esp_hal::time::Rate;
            
            pub use super::generated::ergonomics::*;
        }   

        pub use prelude::*;     

        pub struct Context {
            pub logger: espforge_platform::logger::Logger,
            pub delay: espforge_platform::delay::Delay,
            pub components: generated::Components<'static>,
            pub devices: generated::Devices<'static>,
        }
    };

    let syntax_tree = syn::parse2(tokens).context("Failed to parse generated library structure")?;
    Ok(prettyplease::unparse(&syntax_tree))
}

pub fn generate_entry_point_source(model: &EspforgeConfiguration) -> Result<String> {
    let crate_name = model.get_name().replace('-', "_");
    let crate_ident = quote::format_ident!("{}", crate_name);

    let tokens = quote! {
        #![no_std]
        #![no_main]
        #[warn(unused_variables)]

        // Generated by espforge

        use esp_backtrace as _;
        use esp_hal::main;

        use #crate_ident::{Context, app, generated};
        use espforge_platform as platform;
        use static_cell::StaticCell;
        static REGISTRY: StaticCell<generated::PeripheralRegistry> = StaticCell::new();

        esp_bootloader_esp_idf::esp_app_desc!();

        #[main]
        fn main() -> ! {
            esp_println::logger::init_logger_from_env();
            esp_println::print!("\x1b[20h");

            let config = esp_hal::Config::default();
            let peripherals = esp_hal::init(config);

            let registry = REGISTRY.init(generated::PeripheralRegistry::new(peripherals));
            let components = generated::Components::new(registry);

            let mut delay = platform::delay::Delay::new();
            let mut devices = generated::Devices::new(&components, registry, &mut delay);

            let mut ctx = Context {
                logger: platform::logger::Logger::new(),
                delay,
                components,
                devices,
            };

            // Call setup
            app::setup(&mut ctx);

            loop {
                // Call forever loop
                app::forever(&mut ctx);
            }
        }
    };

    let syntax_tree = syn::parse2(tokens).context("Failed to parse generated main.rs")?;
    Ok(prettyplease::unparse(&syntax_tree))
}



/// Generates the entire `generated.rs`
pub fn generate_components_source(model: &EspforgeConfiguration) -> Result<String> {
    let hardware_struct = generator::hardware::generate_peripheral_registry(model)?;

    // Generate the struct that owns the platform components
    let components_struct = generator::components::generate_component_registry(model)?;

    let devices_struct = generator::devices::generate_device_registry(model)?;

    let output = quote! {
        // Generated by espforge
        #[allow(unused_imports)]
        #[allow(unused_imports)]
        #[allow(unused_variables)]
        #[allow(unused_mut)]


        use esp_hal::{
            gpio::{AnyPin, Io, Pin, Output, Input, Level, OutputConfig, InputConfig, Pull},
            spi::{master::Spi, Mode},
            i2c::master::I2c,
            peripherals::Peripherals,
            Blocking,
        };
        use core::cell::RefCell;
        use core::marker::PhantomData;

        // Platform dependencies for the Component Registry
        use espforge_platform as platform;

        #hardware_struct

        pub mod ergonomics {
            use embedded_hal::digital::{StatefulOutputPin, InputPin, OutputPin};

            /// Adds simple .on() .off() .toggle() methods that panic on error
            /// instead of returning Result.
            pub trait EasyOutput: StatefulOutputPin {
                fn on(&mut self) {
                    self.set_high().unwrap_or_else(|_| panic!("GPIO Error"));
                }
                
                fn off(&mut self) {
                    self.set_low().unwrap_or_else(|_| panic!("GPIO Error"));
                }
                
                fn toggle(&mut self) {
                    StatefulOutputPin::toggle(self).unwrap_or_else(|_| panic!("GPIO Error"));
                }
            }

            // Blanket implementation: This applies the trait to ANY pin that implements the standard trait
            impl<T: StatefulOutputPin> EasyOutput for T {}
            
            /// Adds simple .is_pressed() logic
            pub trait EasyInput: InputPin {
                fn is_pressed(&mut self) -> bool {
                    // Default to active low (pull-up) common for buttons
                    self.is_low().unwrap_or(false)
                }

                fn is_released(&mut self) -> bool {
                    self.is_high().unwrap_or(false)
                }
            }
            
            impl<T: InputPin> EasyInput for T {}
        }
        

        #components_struct

        #devices_struct
    };

    let syntax_tree = syn::parse2(output).context("Failed to parse generated tokens")?;
    Ok(prettyplease::unparse(&syntax_tree))
}

