    fn features(doc: &toml_edit::DocumentMut, dep: &str) -> Vec<String> {
        doc["dependencies"][dep]["features"]
            .as_array()
            .unwrap_or_else(|| panic!("{dep} has no features"))
            .iter()
            .map(|v| v.as_str().unwrap().to_string())
            .collect()
    }
