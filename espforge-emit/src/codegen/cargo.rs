    #[test]
    fn merge_keeps_a_dependency_and_comment_the_user_added() {
        let generated = cargo(true, &[], Runtime::Blocking);
        let previous = generated.replace(
            "static_cell = \"2.1.1\"",
            "static_cell = \"2.1.1\"\nserde = \"1\"          # mine",
        );
        let merged = merge(Some(&previous), &generated).unwrap();
        assert!(merged.warnings.is_empty(), "{:?}", merged.warnings);
        assert!(
            merged.content.contains("serde = \"1\""),
            "{}",
            merged.content
        );
        assert!(merged.content.contains("# mine"), "{}", merged.content);
        assert_eq!(merged.content.matches(MERGED_HEADER).count(), 1);

        // Merging the result again is a fixed point: same bytes, no warnings.
        let again = merge(Some(&merged.content), &generated).unwrap();
        assert_eq!(again.content, merged.content);
        assert!(again.warnings.is_empty(), "{:?}", again.warnings);
    }

