//! Transcribes the option half of `espf.schema.kdl` into checked-in Rust.
//!
//! This is a transcriber, not a validator: it copies the `required` list and the
//! `option` nodes into `src/generated_options.rs` and deliberately has no rules
//! of its own about what a valid option is. The schema loader
//! (`espforge-options/src/schema.rs`) stays the single oracle, and
//! `generated_options::schema()` is asserted equal to `load(SCHEMA_KDL)` by a
//! test — so anything this file gets wrong is a test failure, not a silent
//! divergence, and anything the schema gets wrong still fails there too.
//!
//! `#[rustfmt::skip]` on the generated function keeps the checked-in file
//! byte-identical to what this build script writes; formatting long help
//! strings is not something a generator should try to predict.

use std::fs;
use std::path::Path;

const SCHEMA: &str = "../espforge-espgenerate-template/src/espf.schema.kdl";

fn main() {
    println!("cargo:rerun-if-changed={SCHEMA}");

    let src = fs::read_to_string(SCHEMA).unwrap_or_else(|e| panic!("cannot read {SCHEMA}: {e}"));
    let doc = kdl::KdlDocument::parse_v2(&src)
        .unwrap_or_else(|e| panic!("{SCHEMA} is not valid KDL v2:\n{e}"));

    let mut required: Vec<String> = Vec::new();
    let mut options: Vec<String> = Vec::new();

    for node in doc.nodes() {
        match node.name().value() {
            "required" => required.extend(positional_strings(node)),
            "options" => {
                for child in node.children().map(|c| c.nodes()).unwrap_or(&[]) {
                    if child.name().value() == "option" {
                        options.push(option_literal(child));
                    }
                }
            }
            // The element vocabulary lives in the same file.
            _ => {}
        }
    }

    let required = if required.is_empty() {
        "Vec::new()".to_string()
    } else {
        format!(
            "vec![{}]",
            required
                .iter()
                .map(|name| format!("{name:?}.to_string()"))
                .collect::<Vec<_>>()
                .join(", ")
        )
    };

    let out = format!(
        concat!(
            "// AUTO-GENERATED BY BUILD.RS FROM espf.schema.kdl - DO NOT EDIT MANUALLY\n",
            "\n",
            "//! The option half of `espf.schema.kdl` as Rust.\n",
            "//!\n",
            "//! `schema::embedded_schema` returns this table; a test asserts it equals\n",
            "//! what `schema::load` parses from the embedded text, so the loader stays\n",
            "//! the authority on what the schema means.\n",
            "\n",
            "use crate::schema::{{Compat, Kind, OptValue, OptionDef, Requires, Schema}};\n",
            "\n",
            "#[rustfmt::skip]\n",
            "pub(crate) fn schema() -> Schema {{\n",
            "    Schema {{\n",
            "        required: {required},\n",
            "        options: vec![\n",
            "{options}",
            "        ],\n",
            "    }}\n",
            "}}\n",
        ),
        required = required,
        options = options.join(""),
    );

    write_if_changed(Path::new("src/generated_options.rs"), &out);
}

/// One `OptionDef { .. },` line block for an `option` node.
fn option_literal(node: &kdl::KdlNode) -> String {
    let name = positional_strings(node).remove(0);

    let mut display_name = None;
    let mut selection_group = None;
    let mut kind_name = "bool".to_string();
    let mut nightly = false;
    let mut default = None;
    let mut requires: Vec<String> = Vec::new();
    let mut tools: Vec<String> = Vec::new();
    let mut chips: Option<Vec<String>> = None;
    let mut choices: Vec<String> = Vec::new();
    let mut help = None;

    for entry in node.entries().iter().filter(|e| e.name().is_some()) {
        match entry.name().map(|k| k.value()).unwrap_or("") {
            "display_name" => display_name = entry.value().as_string().map(str::to_string),
            "selection_group" => selection_group = entry.value().as_string().map(str::to_string),
            "kind" => {
                if let Some(kind) = entry.value().as_string() {
                    kind_name = kind.to_string();
                }
            }
            "requires_nightly" => nightly = entry.value().as_bool().unwrap_or(false),
            "default" => {
                default = match entry.value().as_bool() {
                    Some(value) => Some(format!("Some(OptValue::Bool({value}))")),
                    None => entry
                        .value()
                        .as_string()
                        .map(|value| format!("Some(OptValue::Str({value:?}.to_string()))")),
                }
            }
            _ => {}
        }
    }

    for child in node.children().map(|c| c.nodes()).unwrap_or(&[]) {
        match child.name().value() {
            "help" => help = positional_strings(child).into_iter().next(),
            "requires" => requires.extend(positional_strings(child)),
            "requires_tools" => tools.extend(positional_strings(child)),
            "choices" => choices.extend(positional_strings(child)),
            "compatible" => {
                chips = Some(
                    child
                        .children()
                        .map(|c| c.nodes())
                        .unwrap_or(&[])
                        .iter()
                        .filter(|c| c.name().value() == "chip")
                        .flat_map(positional_strings)
                        .collect(),
                )
            }
            _ => {}
        }
    }

    let kind = match kind_name.as_str() {
        "string" => "Kind::String".to_string(),
        "list" => "Kind::List".to_string(),
        "choice" => format!("Kind::Choice({})", string_vec(&choices)),
        _ => "Kind::Bool".to_string(),
    };
    // A bool option is off unless the schema says otherwise, and the loader
    // records that as an explicit `Some(Bool(false))`.
    if kind_name == "bool" && default.is_none() {
        default = Some("Some(OptValue::Bool(false))".to_string());
    }

    let span = node.span();
    let span = format!("{}..{}", span.offset(), span.offset() + span.len());

    format!(
        "            OptionDef {{\n\
         \x20               name: {name:?}.to_string(),\n\
         \x20               display_name: {display_name},\n\
         \x20               help: {help},\n\
         \x20               kind: {kind},\n\
         \x20               default: {default},\n\
         \x20               requires: Requires {{\n\
         \x20                   options: {requires},\n\
         \x20                   tools: {tools},\n\
         \x20                   nightly: {nightly},\n\
         \x20               }},\n\
         \x20               compat: Compat {{ chips: {chips} }},\n\
         \x20               selection_group: {selection_group},\n\
         \x20               span: {span},\n\
         \x20           }},\n",
        display_name = opt_string(display_name),
        help = opt_string(help),
        default = default.unwrap_or_else(|| "None".to_string()),
        requires = string_vec(&requires),
        tools = string_vec(&tools),
        chips = match chips {
            Some(chips) => format!("Some({})", string_vec(&chips)),
            None => "None".to_string(),
        },
        selection_group = opt_string(selection_group),
    )
}

/// `Some("text".to_string())` or `None`.
fn opt_string(value: Option<String>) -> String {
    match value {
        Some(text) => format!("Some({text:?}.to_string())"),
        None => "None".to_string(),
    }
}

/// `vec!["a".to_string(), ..]` or `Vec::new()`.
fn string_vec(values: &[String]) -> String {
    if values.is_empty() {
        return "Vec::new()".to_string();
    }
    format!(
        "vec![{}]",
        values
            .iter()
            .map(|value| format!("{value:?}.to_string()"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn positional_strings(node: &kdl::KdlNode) -> Vec<String> {
    node.entries()
        .iter()
        .filter(|entry| entry.name().is_none())
        .filter_map(|entry| entry.value().as_string().map(str::to_string))
        .collect()
}

/// Keep the checked-in file and the generated one identical, without touching
/// the file (and its mtime) when nothing changed.
fn write_if_changed(path: &Path, contents: &str) {
    let current = fs::read_to_string(path).unwrap_or_default();
    if current != contents {
        fs::write(path, contents)
            .unwrap_or_else(|e| panic!("cannot write {}: {e}", path.display()));
    }
}
