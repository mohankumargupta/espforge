//! Typed wrappers for the ESPF `<*_component>` bus components.
//!
//! Each module wraps one component tag from the ESPF schema
//! (see `examples/example.espf.txt`):
//!
//! - [`gpio_component`] — `<gpio_component id.. gpio="$gpioX" direction="output" />`
//! - [`i2c_component`]  — `<i2c_component id.. i2c="$i2cN" address="0x.." />`
//! - [`spi_component`]  — `<spi_component id.. spi="$spiN" mode="0" cs="$gpioX" />`
//! - [`uart_component`] — `<uart_component id.. uart="$uartN" baud_rate="9600" />`
//!
//! Each wrapper exposes a `resolve(node, ctx) -> Result<Self, String>`
//! constructor that resolves the `$`-parent-peripheral reference through the
//! [`RuntimeContext`] tables. The attributes themselves — which exist, which
//! are required, which values a `choice` or a `range` allows — come from the
//! one element schema, compiled into [`generated_elements`] by `build.rs`;
//! [`attrs`] is the coercion layer that turns a spelling into a typed value
//! with its span. No wrapper reads an attribute by hand any more.

pub mod attrs;
pub mod button_component;
pub mod gpio_component;
pub mod i2c_component;
pub mod led_component;
pub mod spi_component;
pub mod uart_component;

// Generated by build.rs from the one element schema (`espf.schema.kdl`), so
// the list of tags is not written down twice.
mod generated_vocab;

// Also generated by build.rs: one typed `Attrs` struct per element, which the
// wrappers in this directory read their attributes through. Public because it
// is the schema as code: a new consumer should not have to hand-parse either.
pub mod generated_elements;

/// The bus-component tags taken by [`resolve_component`]. Generated from the
/// `components` elements marked `bus_component=#true` in `espf.schema.kdl`.
///
/// `<led>` / `<button>` have their own typed wrappers (`led_component`,
/// `button_component`) for hardware to consume directly; they are components
/// but not bus dispatchers, so they stay out of `TAGS`.
pub use generated_vocab::TAGS;

pub use button_component::ButtonComponent;
pub use gpio_component::{GpioComponent, GpioDirection};
pub use i2c_component::I2cComponent;
pub use led_component::LedComponent;
pub use spi_component::SpiComponent;
pub use uart_component::{Parity, StopBits, UartComponent};

use espf::context::{ParsedNode, RuntimeContext};

/// Resolves any `<*_component>` node to its typed wrapper by tag name.
pub fn resolve_component<'a>(
    node: &'a ParsedNode<'a>,
    ctx: &RuntimeContext<'a>,
) -> Result<Component<'a>, String> {
    match node.tag_name {
        "gpio_component" => Ok(Component::Gpio(GpioComponent::resolve(node, ctx)?)),
        "i2c_component" => Ok(Component::I2c(I2cComponent::resolve(node, ctx)?)),
        "spi_component" => Ok(Component::Spi(SpiComponent::resolve(node, ctx)?)),
        "uart_component" => Ok(Component::Uart(UartComponent::resolve(node, ctx)?)),
        other => Err(format!("❌ Unknown component tag <{other}>")),
    }
}

/// Any typed bus component.
#[derive(Debug, Clone)]
pub enum Component<'a> {
    Gpio(GpioComponent<'a>),
    I2c(I2cComponent<'a>),
    Spi(SpiComponent<'a>),
    Uart(UartComponent<'a>),
}

impl Component<'_> {
    /// The component's `id` attribute value.
    pub fn id(&self) -> &str {
        match self {
            Component::Gpio(c) => c.id,
            Component::I2c(c) => c.id,
            Component::Spi(c) => c.id,
            Component::Uart(c) => c.id,
        }
    }

    /// Handle of the resolved parent peripheral.
    pub fn peripheral_handle(&self) -> espf::context::Handle {
        match self {
            Component::Gpio(c) => c.peripheral_handle,
            Component::I2c(c) => c.peripheral_handle,
            Component::Spi(c) => c.peripheral_handle,
            Component::Uart(c) => c.peripheral_handle,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use espf::context::{AttrOp, TagAttribute};

    fn node(tag: &'static str) -> ParsedNode<'static> {
        ParsedNode {
            tag_name: tag,
            id: "x",
            attributes: Vec::new(),
            offset: 0,
        }
    }

    fn with_attrs(
        tag: &'static str,
        attrs: &[(&'static str, &'static str)],
    ) -> ParsedNode<'static> {
        ParsedNode {
            tag_name: tag,
            id: attrs
                .iter()
                .find(|(key, _)| *key == "id")
                .map(|(_, value)| *value)
                .unwrap_or(""),
            attributes: attrs
                .iter()
                .map(|(key, val)| TagAttribute {
                    key,
                    op: AttrOp::Set,
                    key_offset: 0,
                    val,
                    val_offset: 0,
                })
                .collect(),
            offset: 0,
        }
    }

    /// The generated `TAGS` and this module's `match` cannot drift: every tag
    /// the schema marks `bus_component=#true` reaches a dispatcher arm, and the
    /// elements that are components but not bus dispatchers do not.
    #[test]
    fn the_dispatcher_covers_exactly_the_schema_tags() {
        let ctx = RuntimeContext::new();

        for tag in TAGS {
            let err = resolve_component(&node(tag), &ctx)
                .err()
                .expect("an attribute-less node cannot resolve");
            assert!(
                !err.contains("Unknown component tag"),
                "`{tag}` is a bus component in the schema but has no dispatcher arm: {err}"
            );
        }

        for tag in ["led", "button"] {
            let err = resolve_component(&node(tag), &ctx)
                .err()
                .expect("led/button have separate typed wrappers");
            assert!(
                err.contains("Unknown component tag"),
                "`{tag}` must not be a bus component: {err}"
            );
        }
    }

    /// The schema now decides *whether* an attribute is required and *what
    /// values* it accepts; the wrapper still decides how that reads. These are
    /// the strings the diagnostics corpus and the hardware tests pin, so the
    /// generated layer must not move them.
    #[test]
    fn schema_level_problems_keep_their_wording() {
        let ctx = RuntimeContext::new();

        let n = with_attrs("gpio_component", &[("id", "x"), ("direction", "output")]);
        assert_eq!(
            GpioComponent::resolve(&n, &ctx).unwrap_err(),
            "❌ [gpio_component] 'x' missing required attribute 'gpio'"
        );

        let n = with_attrs("i2c_component", &[("id", "dev"), ("i2c", "$i2c0")]);
        assert_eq!(
            I2cComponent::resolve(&n, &ctx).unwrap_err(),
            "❌ [i2c_component] 'dev' missing required attribute 'address'"
        );

        let n = with_attrs(
            "i2c_component",
            &[("id", "dev"), ("i2c", "$i2c0"), ("address", "0xZZ")],
        );
        assert_eq!(
            I2cComponent::resolve(&n, &ctx).unwrap_err(),
            "❌ [i2c_component] 'dev' invalid hex address '0xZZ'"
        );

        let n = with_attrs("spi_component", &[("id", "d"), ("spi", "$spi2")]);
        assert_eq!(
            SpiComponent::resolve(&n, &ctx).unwrap_err(),
            "❌ [spi_component] 'd' missing required attribute 'cs'"
        );

        let n = with_attrs(
            "spi_component",
            &[("id", "d"), ("spi", "$spi2"), ("mode", "4"), ("cs", "9")],
        );
        assert_eq!(
            SpiComponent::resolve(&n, &ctx).unwrap_err(),
            "❌ [spi_component] 'd' invalid mode '4': expected 0..=3"
        );

        let n = with_attrs("uart_component", &[("id", "u"), ("uart", "$uart1")]);
        assert_eq!(
            UartComponent::resolve(&n, &ctx).unwrap_err(),
            "❌ [uart_component] 'u' missing required attribute 'baud_rate'"
        );

        let n = with_attrs(
            "uart_component",
            &[
                ("id", "u"),
                ("uart", "$uart1"),
                ("baud_rate", "9600"),
                ("parity", "weird"),
            ],
        );
        assert_eq!(
            UartComponent::resolve(&n, &ctx).unwrap_err(),
            "❌ [uart_component] Invalid parity 'weird': expected \"none\", \"even\" or \"odd\""
        );

        let n = with_attrs("led", &[("id", "l")]);
        assert_eq!(
            LedComponent::resolve(&n, &ctx).unwrap_err(),
            "<led id=\"l\"> needs gpio=\"$<gpio id>\""
        );

        let n = with_attrs("led", &[("id", "l"), ("gpio", "$g"), ("active_low", "yes")]);
        assert_eq!(
            LedComponent::resolve(&n, &ctx).unwrap_err(),
            "<led id=\"l\"> active_low=\"yes\" must be \"true\" or \"false\""
        );

        let n = with_attrs("button", &[("id", "b")]);
        assert_eq!(
            ButtonComponent::resolve(&n, &ctx).unwrap_err(),
            "<button id=\"b\"> needs gpio=\"$<gpio id>\""
        );
    }
}
