use std::fs;
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=src/drivers");

    let drivers_dir = Path::new("src/drivers");
    let dest_path = Path::new("src/generated_registry.rs");

    let mut modules = Vec::new();
    let mut match_arms = Vec::new();

    if let Ok(entries) = fs::read_dir(drivers_dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            println!("cargo:rerun-if-changed={}", path.display());
            if path.extension().map_or(false, |ext| ext == "rs") {
                let stem = path.file_stem().unwrap().to_str().unwrap().to_string();
                if stem != "mod" {
                    // #[path] is relative to src/ (the directory containing
                    // generated_registry.rs), so "drivers/tmp102.rs" resolves
                    // to src/drivers/tmp102.rs.
                    modules.push(format!(
                        "#[path = \"drivers/{stem}.rs\"]\npub mod {stem};"
                    ));
                    match_arms.push(format!(
                        "        \"{stem}\" => {stem}::init(device, ctx),"
                    ));
                }
            }
        }
    }

    let generated_code = format!(
        "// AUTO-GENERATED BY BUILD.RS - DO NOT EDIT MANUALLY\n\n\
        #[allow(dead_code)]\n\
        {}\n\n\
        pub fn route_driver(tag_name: &str, device: &crate::context::ResolvedDevice, ctx: &crate::context::RuntimeContext) -> Result<(), String> {{\n\
            match tag_name {{\n\
        {}\n\
                _ => Err(format!(\"❌ No compile-time driver engine found for runtime tag <{{}}>\", tag_name)),\n\
            }}\n\
        }}",
        modules.join("\n"),
        match_arms.join("\n")
    );

    let current_content = fs::read_to_string(dest_path).unwrap_or_default();
    if current_content != generated_code {
        fs::write(dest_path, generated_code).unwrap();
    }
}